async function main() {
  for (const t of TASKS) {
    const existing = await prisma.practiceTask.findFirst({ where: { name: t.name } });
    if (existing) {
      await prisma.practiceTask.update({
        where: { id: existing.id },
        data: { ...t, isActive: true },
      });
      console.log(`${t.name}: обновлён`);
    } else {
      await prisma.practiceTask.create({ data: { ...t, category: "builder" } });
      console.log(`${t.name}: создан`);
    }
  }
  console.log("Готово: 3 практических задания.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
