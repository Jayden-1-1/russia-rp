async function upsertTemplate(name: string, category: string, questions: { text: string; criteria?: string; qtype?: string }[]) {
  const existing = await prisma.callTemplate.findFirst({ where: { name } });
  let templateId: string;
  if (existing) {
    await prisma.question.deleteMany({ where: { templateId: existing.id } });
    templateId = existing.id;
    await prisma.callTemplate.update({
      where: { id: existing.id },
      data: { category, isActive: true },
    });
  } else {
    const t = await prisma.callTemplate.create({ data: { name, category } });
    templateId = t.id;
  }
  let order = 1;
  for (const q of questions) {
    await prisma.question.create({
      data: {
        templateId,
        order: order++,
        text: q.text,
        type: q.qtype ?? "short_text",
        criteria: q.criteria ?? undefined,
        points: 2,
      },
    });
  }
  return order - 1;
}

async function main() {
  // Роли
  for (const r of BASE_ROLES) {
    const existing = await prisma.role.findUnique({ where: { name: r.name } });
    if (existing) {
      // обновляем права
      const perms = await prisma.rolePermission.findMany({ where: { roleId: existing.id } });
      for (const p of perms) {
        await prisma.rolePermission.update({
          where: { id: p.id },
          data: { allowed: r.capabilities.includes(p.capability) },
        });
      }
      for (const cap of r.capabilities) {
        const p = perms.find((x) => x.capability === cap);
        if (!p) {
          await prisma.rolePermission.create({
            data: { roleId: existing.id, capability: cap, allowed: true },
          });
        }
      }
      console.log(`Роль «${r.name}» обновлена`);
    } else {
      await prisma.role.create({
        data: {
          name: r.name,
          description: r.description,
          permissions: {
            create: r.capabilities.map((capability) => ({ capability, allowed: true })),
          },
        },
      });
      console.log(`Роль «${r.name}» создана`);
    }
  }

  // Правила RP: 3 варианта (6 личных + 25 правил)
  for (let v = 0; v < RULES_VARIANTS.length; v++) {
    const qs = PART1_RP.map((t) => ({
      text: t,
      criteria: "Личная беседа — оценивается администрацией (0–2 балла)",
    }));
    for (const [q, a] of RULES_VARIANTS[v]) {
      qs.push({ text: q, criteria: `Правильный ответ: ${a}` });
    }
    const n = await upsertTemplate(`RP Вариант ${v + 1}`, "rules", qs);
    console.log(`RP Вариант ${v + 1}: ${n} вопросов`);
  }

  // Билдер-скриптер: 3 варианта по 25 вопросов
  for (let v = 0; v < BUILDER_VARIANTS.length; v++) {
    const qs = BUILDER_VARIANTS[v].map((text, i) => ({
      text: `${i + 1}. ${text}`,
      criteria: "Оценивается администрацией (0–2 балла)",
    }));
    const n = await upsertTemplate(`Билдер-скриптер Вариант ${v + 1}`, "builder", qs);
    console.log(`Билдер-скриптер Вариант ${v + 1}: ${n} вопросов`);
  }

  console.log("Готово.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
